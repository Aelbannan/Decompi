/**
 * M1b tests for the symbols.txt loader + MWCC mangled-name parser
 * (`src/parse/symbols/table.ts`): port of
 * `tools/symbolrecover/lib/parser.py` (load_symbols) and the `__Q…`
 * qualifier parsing in `tools/coop/member_check.py` against the real
 * `config/us/symbols.txt` format.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { loadSymbols, parseMangled } from "../src/parse/symbols/table.js";

const SNIPPET = `# generated by decomp-toolkit
memcpy = .init:0x80004000; // type:function size:0x29C scope:global
__start = .init:0x80006310; // type:function size:0x16C scope:weak

// extab data bucket
@4558 = extab:0x800066E0; // type:object size:0x1C scope:local hidden
func_80047814__Q22cf13CfObjectPointFv = .text:0x80047814; // type:function size:0x54 scope:global
func_80137038 = .text:0x80137038; // type:function size:0x1C scope:global
lbl_80137038 = .text:0x80137038; // type:label scope:local
tolerant_no_section = 0x80200000; // type:function
`;

test("loadSymbols: byAddress / byName lookups", () => {
  const t = loadSymbols(SNIPPET);
  assert.deepEqual(t.byAddress.get(0x80004000), ["memcpy"]);
  assert.equal(t.byName.get("memcpy"), 0x80004000);
  assert.deepEqual(t.byAddress.get(0x80047814), ["func_80047814__Q22cf13CfObjectPointFv"]);
  assert.equal(t.byName.get("__start"), 0x80006310);
  assert.deepEqual(t.byAddress.get(0x800066E0), ["@4558"]);
  // tolerant form without a section
  assert.equal(t.byName.get("tolerant_no_section"), 0x80200000);
  assert.deepEqual(t.byAddress.get(0x80200000), ["tolerant_no_section"]);
  // two names aliased to one address: byName keeps both (first wins), and
  // byAddress keeps ALL occupants in file order (Python addr_hits parity —
  // the func_X / lbl_X alias is what makes jp-stale detection correct)
  assert.equal(t.byName.get("func_80137038"), 0x80137038);
  assert.equal(t.byName.get("lbl_80137038"), 0x80137038);
  assert.equal(t.byName.size, 7);
  assert.equal(t.byAddress.size, 6);
  assert.deepEqual(t.byAddress.get(0x80137038), ["func_80137038", "lbl_80137038"]);
});

test("loadSymbols: byName is first-wins for duplicate names (setdefault parity)", () => {
  const t = loadSymbols("dup = .text:0x80004000;\ndup = .text:0x80005000;\n");
  // Python `names.setdefault(name, reg)` keeps the FIRST occurrence
  assert.equal(t.byName.get("dup"), 0x80004000);
  assert.deepEqual(t.byAddress.get(0x80004000), ["dup"]);
  assert.deepEqual(t.byAddress.get(0x80005000), ["dup"]);
});

test("loadSymbols: comments and blank lines are ignored", () => {
  const t = loadSymbols(
    "// a comment\n\n# another comment\n   \nmemcpy = .init:0x80004000;\nmemmove = .text:0x80000000 // no trailing semicolon\n",
  );
  assert.equal(t.byName.get("memcpy"), 0x80004000);
  assert.equal(t.byName.get("memmove"), 0x80000000);
  assert.deepEqual(t.byAddress.get(0x80004000), ["memcpy"]);
  assert.deepEqual(t.byAddress.get(0x80000000), ["memmove"]);
  assert.equal(t.byName.size, 2);
  assert.equal(t.byAddress.size, 2);
});

test("loadSymbols: malformed lines are skipped", () => {
  const t = loadSymbols("garbage line without equals\n= 0x80004000;\nmemcpy = 0x;\n");
  assert.equal(t.byName.size, 0);
  assert.equal(t.byAddress.size, 0);
});

test("parseMangled: __ct__ constructor", () => {
  const m = parseMangled("__ct__11CGameFv");
  assert.equal(m.isMember, true);
  assert.equal(m.isConstructor, true);
  assert.equal(m.isDestructor, false);
  assert.equal(m.className, "CGame");
  assert.equal(m.params, "v");
  assert.deepEqual(m.namespacePath, []);
});

