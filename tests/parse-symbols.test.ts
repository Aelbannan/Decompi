test("parseMangled: free names are not members", () => {
  for (const name of [
    "func_80137038",
    "lbl_80137038",
    "data_80006000",
    "memcpy",
    "__start",
    "__init_registers",
    "__sinit_CfGameManager_cpp",
    "__800B0AF4",
    "@4558",
    "@etb_800067C4",
    "gTRKInterruptVectorTable",
  ]) {
    const m = parseMangled(name);
    assert.equal(m.isMember, false, `${name} should be free`);
    assert.equal(m.className, null, `${name} should have no class`);
  }
});

test("parseMangled: anonymous-namespace qualifier is a real token (108/116 real @unnamed symbols)", () => {
  // dtk renders an anonymous namespace as `@unnamed@<file>_cpp@` INSIDE the
  // qualifier; only known dtk local suffixes (`@instance`, `@<digits>`) are
  // stripped before parsing, so the qualifier survives.
  const m = parseMangled("wkUpdate__Q219@unnamed@CGame_cpp@12CGameRestartFv");
  assert.equal(m.isMember, true);
  assert.equal(m.className, "CGameRestart");
  assert.deepEqual(m.namespacePath, ["@unnamed@CGame_cpp@", "CGameRestart"]);
  assert.equal(m.params, "v");

  const d = parseMangled("__dt__Q219@unnamed@CGame_cpp@12CGameRestartFv");
  assert.equal(d.isMember, true);
  assert.equal(d.isDestructor, true);
  assert.equal(d.className, "CGameRestart");

  // unqualified anonymous-namespace class token: `__<len>@unnamed@…F<params>`
  const u = parseMangled("GetFreePlayer__24@unnamed@HBMAxSound_cpp@Fi");
  assert.equal(u.isMember, true);
  assert.equal(u.className, "@unnamed@HBMAxSound_cpp@");
  assert.equal(u.params, "i");
});

test("parseMangled: bucket prefixes and data members with @ tokens", () => {
  const m = parseMangled("@GUARD@mDefaultTagProcessor__Q36nw4hbm2ut17TextWriterBase<c>");
  assert.equal(m.isMember, true);
  assert.equal(m.className, "TextWriterBase<c>");
  assert.deepEqual(m.namespacePath, ["nw4hbm", "ut", "TextWriterBase<c>"]);
  assert.equal(m.params, null);

  const n = parseMangled("@LOCAL@getInstance__Q22ml6MTRandFv@instance");
  assert.equal(n.isMember, true);
  assert.equal(n.className, "MTRand");
  assert.deepEqual(n.namespacePath, ["ml", "MTRand"]);
  assert.equal(n.params, "v");
});

test("parseMangled: dtk local suffixes (@instance, @<digits>) still stripped", () => {
  const m = parseMangled("@LOCAL@getInstance__Q22ml6MTRandFv@instance");
  assert.equal(m.isMember, true);
  assert.equal(m.className, "MTRand");
  assert.equal(m.params, "v");
  const b = parseMangled("wkUpdate__Q219@unnamed@CGame_cpp@12CGameRestartFv@4");
  assert.equal(b.isMember, true);
  assert.equal(b.className, "CGameRestart");
  assert.equal(b.params, "v");
});
